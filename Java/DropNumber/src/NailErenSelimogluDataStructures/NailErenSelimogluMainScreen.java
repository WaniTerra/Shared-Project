    private void mergedLabels(JLabel l1, int absoluteTargetY, Runnable onComplete) {
        final int opTime = 6;
        NailErenSelimogluNode node = (NailErenSelimogluNode) location.get(count)[0];
        int value = node.data;
        l1.setText(String.valueOf(value));
        labelColor(l1, value);
        l1.setForeground(new Color(l1.getForeground().getRed(), l1.getForeground().getGreen(), l1.getForeground().getBlue(), 0));
        Timer timer = new Timer(15, new ActionListener() {
            int alpha = 0;
            int currentY = l1.getY();
            int speed = 5;

            @Override
            public void actionPerformed(ActionEvent e) {

                alpha += opTime;
                if (alpha > 255) {
                    alpha = 255;
                }

                if (currentY < absoluteTargetY) {
                    currentY += speed;
                    if (currentY > absoluteTargetY) {
                        currentY = absoluteTargetY;
                    }
                    l1.setLocation(l1.getX(), currentY);
                }

                l1.setForeground(new Color(255, 255, 255, alpha));

                if (alpha >= 255 && currentY >= absoluteTargetY) {
                    ((Timer) e.getSource()).stop();

                    Component[] components = panelMain.getComponents();
                    Rectangle targetArea = new Rectangle(l1.getX(), absoluteTargetY, 54, 54);

                    for (Component comp : components) {
                        if (comp instanceof JLabel && comp != l1) {
                            if (targetArea.intersects(comp.getBounds())) {
                                comp.setVisible(false);
                                panelMain.remove(comp);
                            }
                        }
                    }

                    panelMain.remove(l1);
                    panelMain.add(l1, new org.netbeans.lib.awtextra.AbsoluteConstraints(l1.getX(), absoluteTargetY, 54, 54));
                    panelMain.setComponentZOrder(l1, 0);

                    panelMain.revalidate();
                    panelMain.repaint();

                    Timer pauseTimer = new Timer(100, new ActionListener() {
                        @Override
                        public void actionPerformed(ActionEvent evt) {

                            if (onComplete != null) {
                                onComplete.run();
                            }
                        }
                    });

                    pauseTimer.setRepeats(false);
                    pauseTimer.start();
                }
            }
        });

        timer.start();
    }

    private void labelColor(JLabel label, int value) {
        int level = 0;
        int temp = value;

        while (temp > 1) {
            temp = temp / 2;
            level++;
        }

        float hue = (level * 0.12f) % 1.0f;
        float saturation = 0.85f;
        float brightness = 0.95f;

        Color vibrantColor = Color.getHSBColor(hue, saturation, brightness);

        label.setOpaque(true);
        label.setBackground(vibrantColor);

        label.setForeground(Color.WHITE);
    }

