    private void btnOnebyOneActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnOnebyOneActionPerformed

        btnOnebyOne.setEnabled(false);

        Object[] currentData = location.get(count);
        NailErenSelimogluNode node = (NailErenSelimogluNode) currentData[0];
        int value = node.data;
        int x = (int) currentData[1];
        int y = START_Y;
        int targetY = (int) currentData[2];

        JLabel label = new JLabel(String.valueOf(value));
        label.setFont(new Font("Arial", Font.BOLD, 30));
        label.setHorizontalAlignment(SwingConstants.CENTER);

        labelColor(label, value);

        panelMain.add(label, new org.netbeans.lib.awtextra.AbsoluteConstraints(x, y, 54, 54));
        panelMain.setComponentZOrder(label, 0);
        panelMain.revalidate();
        panelMain.repaint();

        Timer timer = new Timer(15, new ActionListener() {
            int currentY = y;
            int speed = 10;

            @Override
            public void actionPerformed(ActionEvent e) {
                if (currentY < targetY) {
                    currentY += speed;
                    if (currentY > targetY) {
                        currentY = targetY;
                    }
                    label.setLocation(x, currentY);
                } else {

                    ((Timer) e.getSource()).stop();

                    panelMain.remove(label);
                    panelMain.add(label, new org.netbeans.lib.awtextra.AbsoluteConstraints(x, targetY, 54, 54));

                    panelMain.setComponentZOrder(label, 0);

                    panelMain.revalidate();
                    panelMain.repaint();

                    Timer mergeTimer = new Timer(850, null);
                    mergeTimer.addActionListener(new ActionListener() {
                        @Override
                        public void actionPerformed(ActionEvent e2) {

                            if (gameList.merge(gameList) == 1) {
                                ((Timer) e2.getSource()).stop();

                                int absoluteTargetY = ROW[node.row];

                                mergedLabels(label, absoluteTargetY, new Runnable() {
                                    @Override
                                    public void run() {
                                        mergeTimer.start();
                                    }
                                });

                                currentData[2] = absoluteTargetY;

                            } else {
                                ((Timer) e2.getSource()).stop();

                                if (gameList.rowsFilled()) {
                                    labelGf.setVisible(true);
                                    btnAnimated.setEnabled(false);
                                    btnOnebyOne.setEnabled(false);
                                    return;
                                }

                                btnOnebyOne.setEnabled(true);
                                count++;

                                if (count <= TILE_SEQUENCE.length) {
                                    int val = TILE_SEQUENCE[count][0];
                                    int c = TILE_SEQUENCE[count][1];

                                    int rowPx = ROW[gameList.rowFinder(c)];
                                    location.add(new Object[]{gameList.add(val, c), COL[c], rowPx});
                                }

                            }
                        }
                    });

                    mergeTimer.setInitialDelay(0);
                    mergeTimer.start();

                }
            }
        });

        timer.start();


    }//GEN-LAST:event_btnOnebyOneActionPerformed

