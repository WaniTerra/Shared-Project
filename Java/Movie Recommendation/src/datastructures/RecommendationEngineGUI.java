    private void btnGetRecommendationsUserActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGetRecommendationsUserActionPerformed
        try {

            int userCount = Integer.valueOf(txtUserNumberUser.getText().trim());
            int movieCount = Integer.valueOf(txtMovieNumberUser.getText().trim());
            int targetNodeId = Integer.valueOf(comboTargetUser.getSelectedItem().toString());

            MyLinkedList<String> results = engine.getUserRecommendation(mainUsers, targetUsers, targetNodeId, userCount, movieCount);

            StringBuilder sb = new StringBuilder();

            if (results.getHead() == null) {
                sb.append("There is no advice for this user, change the user or\n increase the user or movie number");
            } else {
                int count = 1;
                Node<String> curr = results.getHead();
                while (curr != null) {
                    sb.append(count).append(" - ").append(curr.data).append("\n");
                    curr = curr.next;
                    count++;
                }
            }

            txtResultsUser.setText(sb.toString());

        } catch (NumberFormatException e) {
            txtResultsUser.setText("Enter valid numbers.");
        }


    }//GEN-LAST:event_btnGetRecommendationsUserActionPerformed

    private void btnGetRecommendationsRatingActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGetRecommendationsRatingActionPerformed

        try {

            if (txtUserNumberRating.getText().trim().isEmpty() || txtMovieNumberRating.getText().trim().isEmpty()) {
                txtResultsRating.setText("Enter valid numbers.");
                return;
            }

            int userCount = Integer.valueOf(txtUserNumberRating.getText().trim());
            int movieCount = Integer.valueOf(txtMovieNumberRating.getText().trim());

            MyLinkedList<Integer> votedMovieIds = new MyLinkedList<>();
            MyLinkedList<Integer> votedRatings = new MyLinkedList<>();

            javax.swing.JComboBox[] movieCombos = {comboMovie1, comboMovie2, comboMovie3, comboMovie4, comboMovie5};
            javax.swing.JTextField[] ratingFields = {txtRating1, txtRating2, txtRating3, txtRating4, txtRating5};

            for (int i = 0; i < 5; i++) {
                if (ratingFields[i].getText().trim().isEmpty()) {
                    javax.swing.JOptionPane.showMessageDialog(null,
                            "Please enter all ratings first.",
                            "Warning",
                            javax.swing.JOptionPane.WARNING_MESSAGE);
                    return;
                }
            }

            for (int i = 0; i < 5; i++) {
                String ratingStr = ratingFields[i].getText().trim();

                if (!ratingStr.isEmpty()) {
                    int rating = Integer.parseInt(ratingStr);

                    if (rating >= 1 && rating <= 5) {
                        String selectedMovieInfo = movieCombos[i].getSelectedItem().toString();
                        int movieId = Integer.parseInt(selectedMovieInfo.split(" - ")[0].trim());

                        votedMovieIds.add(movieId);
                        votedRatings.add(rating);
                    }
                }
            }

            MyLinkedList<String> results = RecommendationEngine.getCustomRatingRecommendation(mainUsers, votedMovieIds, votedRatings, userCount, movieCount);

            StringBuilder sb = new StringBuilder();

            if (results.getHead() == null) {
                sb.append("There is no advice for this points, change the points or\n increase the user or movie number");
            } else {
                int count = 1;
                Node<String> curr = results.getHead();
                while (curr != null) {
                    sb.append(count).append(" - ").append(curr.data).append("\n");
                    curr = curr.next;
                    count++;
                }
            }

            txtResultsRating.setText(sb.toString());

        } catch (NumberFormatException e) {
            txtResultsRating.setText("Enter valid numbers.");
        }


    }//GEN-LAST:event_btnGetRecommendationsRatingActionPerformed

