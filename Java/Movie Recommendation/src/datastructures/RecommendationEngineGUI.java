    private void loadDataAndPopulateUI() {
        mainUsers = FileLoader.loadUsers("src\\datastructures\\main_data.csv");
        targetUsers = FileLoader.loadTargetUsers("src\\datastructures\\target_user.csv");

        engine = new RecommendationEngine(mainUsers);
        engine.loadMovies("src\\datastructures\\movies.csv");

        comboTargetUser.removeAllItems();
        Node<User> currTarget = targetUsers.getHead();
        while (currTarget != null) {
            comboTargetUser.addItem(String.valueOf(currTarget.data.getUserId()));
            currTarget = currTarget.next;
        }

        MyLinkedList<Movie> randomMovies = engine.getRandomMovies(10);
        javax.swing.JComboBox[] movieCombos = {comboMovie1, comboMovie2, comboMovie3, comboMovie4, comboMovie5};

        for (int i = 0; i < movieCombos.length; i++) {
            movieCombos[i].removeAllItems();
            Node<Movie> currMovie = randomMovies.getHead();
            while (currMovie != null) {
                movieCombos[i].addItem(currMovie.data.getId() + " - " + currMovie.data.getName());
                currMovie = currMovie.next;
            }
        }
    }

