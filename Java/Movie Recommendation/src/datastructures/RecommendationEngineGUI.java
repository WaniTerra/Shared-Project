    private void controlCombo() {
        if (lock) {
            return;
        }
        for (int i = 0; i < movieCombos.length; i++) {
            final javax.swing.JComboBox currentCombo = movieCombos[i];

            Object selected = currentCombo.getSelectedItem();
            if (selected == null) {
                return;
            }

            boolean isDuplicate = false;

            for (javax.swing.JComboBox otherCombo : movieCombos) {
                if (otherCombo != currentCombo && selected.equals(otherCombo.getSelectedItem())) {
                    isDuplicate = true;
                    break;
                }
            }

            if (isDuplicate) {
                javax.swing.JOptionPane.showMessageDialog(null,
                        "You have already chosen this!\nPlease choose different movie.",
                        "Same movie cannot be selected",
                        javax.swing.JOptionPane.WARNING_MESSAGE);

                int lastValid = (int) currentCombo.getClientProperty("lastValidIndex");
                currentCombo.setSelectedIndex(lastValid);

            } else {
                currentCombo.putClientProperty("lastValidIndex", currentCombo.getSelectedIndex());
            }
        }
    }

    private void controlRatingTxt(String text, javax.swing.JTextField txtField) {

        if (text.isEmpty()) {
            return;
        }

        try {
            int ratingValue = Integer.valueOf(text);

            if (ratingValue < 1 || ratingValue > 5) {
                javax.swing.JOptionPane.showMessageDialog(null,
                        "Enter number between 1 - 5 !",
                        "Invalid number",
                        javax.swing.JOptionPane.ERROR_MESSAGE);

                txtField.setText("");
            }
        } catch (NumberFormatException e) {
            txtField.setText("");
        }
    }

    private void controlTxts(String text, javax.swing.JTextField txtField) {
        if (text.isEmpty()) {
            return;
        }

        if (text.charAt(0) == '0') {
            javax.swing.JOptionPane.showMessageDialog(null,
                    "Number cannot start with 0!",
                    "Invalid Input",
                    javax.swing.JOptionPane.ERROR_MESSAGE);
            txtField.setText("");
            return;
        }

        for (int i = 0; i < text.length(); i++) {
            char c = text.charAt(i);

            if (c < '0' || c > '9') {
                javax.swing.JOptionPane.showMessageDialog(null,
                        "Please enter numbers only!",
                        "Invalid Input",
                        javax.swing.JOptionPane.ERROR_MESSAGE);

                txtField.setText("");
                break;
            }
        }
    }

